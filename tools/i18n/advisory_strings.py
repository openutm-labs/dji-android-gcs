"""Writes app-common's strings_advisories.xml from the core's warning templates (Advisory.of), so the
English resource and the core's English text can't drift. Also writes AdvisoryStrings.kt (key -> resource id). Run from apps/dji-flight after changing a warning:
    python3 -I tools/i18n/advisory_strings.py
Translations go in app-common/src/main/res/values-<lang>/strings_advisories.xml with the same names."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
sources = [root / "core/src/main/kotlin/org/openutm/djiflight/core/advisory/FlightAdvisor.kt",
           root / "core/src/main/kotlin/org/openutm/djiflight/core/terrain/Terrain.kt"]
def calls(text):
    """Each Advisory.of( ... ) call's argument text, brackets and string literals respected."""
    i = 0
    while (i := text.find("Advisory.of(", i)) >= 0:
        j, depth, in_str = i + len("Advisory.of("), 1, False
        while depth:
            c = text[j]
            if in_str:
                if c == "\\": j += 1
                elif c == '"': in_str = False
            elif c == '"': in_str = True
            elif c == "(": depth += 1
            elif c == ")": depth -= 1
            j += 1
        yield text[i + len("Advisory.of("):j - 1]
        i = j
literal = re.compile(r'"((?:[^"\\]|\\.)*)"')
entries = {}
for src in sources:
    for args in calls(src.read_text()):
        strings = literal.findall(args)
        code, template = strings[0], strings[1]
        key = (re.search(r'key = "([A-Z_]+)"', args) or [None, code])[1]
        text = template.replace("${'$'}", "$")
        if key in entries and entries[key] != text:
            raise SystemExit(f"{key}: two different templates")
        entries[key] = text
def xml(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"')
    return s
out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- Generated by tools/i18n/advisory_strings.py from the core\'s Advisory.of(...) templates: edit those, not this file. -->',
       '<resources>']
for key in sorted(entries):
    out.append(f'    <string name="adv_{key.lower()}">{xml(entries[key])}</string>')
out.append('</resources>\n')
path = root / "app-common/src/main/res/values/strings_advisories.xml"
path.write_text("\n".join(out))
kt = root / "app-common/src/main/kotlin/org/openutm/djiflight/app/AdvisoryStrings.kt"
lines = ["package org.openutm.djiflight.app", "",
         "// Generated by tools/i18n/advisory_strings.py from the core's Advisory.of(...) templates: edit those, not this file.", "",
         "/** The string resource for a warning's key, or null for one the app has no resource for. */",
         "internal fun advisoryString(key: String): Int? = when (key) {"]
lines += [f'    "{k}" -> R.string.adv_{k.lower()}' for k in sorted(entries)]
lines += ["    else -> null", "}", ""]
kt.write_text("\n".join(lines))
print(f"{len(entries)} warnings -> {path.relative_to(root)}, {kt.relative_to(root)}")
